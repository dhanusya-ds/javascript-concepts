// arithmetic operators
let a = 2+5;
let b = 10-9;
let c = 8*3;
let d = 9/2;
console.log(a);
console.log(b);
console.log(c);
console.log(d);

// assignment operators
let m = 4;
m += 6;
m *= 2;
console.log(m);

// comparison operators
let x = 5;
let y = 10;
console.log(x == y); 
console.log(x != y);
console.log(x < y); 
console.log(x > y); 
console.log(x <= y); 
console.log(x >= y); 

// logical operators
let p = true;
let q = false;
console.log(p && q);
console.log(p || q); 
console.log(!p);

// bitwise operators
const n1 = 0 & 1;
console.log(n1);

// ternary operator
let age = 19;
let canVote = (age >= 18) ? "Yes" : "No";
console.log(canVote);

// unary operators
let num = 5;
console.log(+num);
console.log(-num);
console.log(++num);
console.log(--num);
console.log(!num);
